import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

export const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function leafKeys(value, prefix = '') {
  return Object.entries(value).flatMap(([key, child]) => {
    const name = prefix ? `${prefix}.${key}` : key;
    if (typeof child === 'string') return [name];
    if (child && typeof child === 'object' && !Array.isArray(child)) return leafKeys(child, name);
    throw Error(`Invalid translation value: ${name}`);
  });
}

function valueAt(value, key) {
  return key.split('.').reduce((node, part) => node?.[part], value);
}

function placeholders(text) {
  return [...text.matchAll(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g)]
    .map((match) => match[1])
    .sort()
    .join(',');
}

async function sourceFiles(directory) {
  const files = await Promise.all(
    (await readdir(directory, { withFileTypes: true })).map(async (entry) => {
      const target = path.join(directory, entry.name);
      if (entry.isDirectory()) return sourceFiles(target);
      return /\.(mjs|js)$/.test(entry.name) ? [target] : [];
    }),
  );
  return files.flat().sort();
}

async function readBuildResources(root) {
  const directory = path.join(root, 'locale');
  const config = JSON.parse(await readFile(path.join(directory, 'config.json'), 'utf8'));
  const locales = new Map();
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isFile() || !entry.name.endsWith('.json') || entry.name === 'config.json') continue;
    const code = entry.name.slice(0, -5);
    if (Intl.getCanonicalLocales(code)[0] !== code)
      throw Error(`Use a canonical language tag: ${code}`);
    locales.set(code, JSON.parse(await readFile(path.join(directory, entry.name), 'utf8')));
  }
  const baseline = locales.get(config.defaultLocale);
  if (!baseline) throw Error(`Default language resource missing: ${config.defaultLocale}`);
  for (const section of ['meta', 'ui', 'errors', 'host']) {
    if (!baseline[section]) throw Error(`Default language section missing: ${section}`);
  }
  const baselineKeys = leafKeys(baseline).sort();
  for (const [code, resource] of locales) {
    if (JSON.stringify(leafKeys(resource).sort()) !== JSON.stringify(baselineKeys)) {
      throw Error(`Translation keys differ: ${code}`);
    }
    for (const key of baselineKeys) {
      const translated = valueAt(resource, key);
      if (!translated.trim()) throw Error(`Empty translation: ${code}.${key}`);
      if (placeholders(translated) !== placeholders(valueAt(baseline, key))) {
        throw Error(`Translation placeholders differ: ${code}.${key}`);
      }
    }
  }
  for (const file of await sourceFiles(path.join(root, 'src'))) {
    const source = await readFile(file, 'utf8');
    for (const [, key] of source.matchAll(/\bt\('([^']+)'\)/g)) {
      if (!key.startsWith('errors.') && !(key in baseline.ui)) {
        throw Error(`UI translation key missing: ${key}`);
      }
    }
  }
  const dictionaries = Object.fromEntries(
    [...locales].map(([code, resource]) => [
      code,
      {
        ...resource.ui,
        ...Object.fromEntries(
          Object.entries(resource.errors).map(([key, value]) => [`errors.${key}`, value]),
        ),
      },
    ]),
  );
  return {
    locales: [...locales.keys()],
    keys: baselineKeys.length,
    resources: { dictionaries, errorCodes: Object.keys(baseline.errors).sort() },
  };
}

/** Build standard ESM source into the host's single browser-loader artifact. */
export async function buildClient(root = projectRoot, { write = true } = {}) {
  const metadata = await readBuildResources(root);
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['src/client.js'],
    bundle: true,
    write: false,
    platform: 'browser',
    format: 'iife',
    target: 'es2023',
    charset: 'utf8',
    legalComments: 'none',
    loader: { '.css': 'text' },
    banner: { js: '// Generated by scripts/build.mjs. Edit src/client/ and locale/ instead.' },
    plugins: [
      {
        name: 'session-terms-locales',
        setup(builder) {
          builder.onResolve({ filter: /^session-terms:locales$/ }, () => ({
            path: 'session-terms:locales',
            namespace: 'session-terms',
          }));
          builder.onLoad({ filter: /.*/, namespace: 'session-terms' }, () => ({
            contents: `export default ${JSON.stringify(metadata.resources)};`,
            loader: 'js',
          }));
        },
      },
    ],
  });
  const output = result.outputFiles[0].text;
  if (write) await writeFile(path.join(root, 'client.js'), output, 'utf8');
  return { ...metadata, output };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildClient();
  console.log(JSON.stringify({ locales: result.locales, translationKeys: result.keys }));
}
